-- Schema PostgreSQL for EduSuivi (PostgreSQL 10+).
-- Apply this script to an empty database. Role rows are seeded separately
-- by database/jaas-roles.sql.

CREATE TABLE annee_academique (
    id_annee BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(30) NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    statut VARCHAR(20) NOT NULL
);

CREATE TABLE departement (
    id_departement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    nom VARCHAR(150) NOT NULL
);

CREATE TABLE utilisateur (
    id_utilisateur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    statut VARCHAR(20) NOT NULL,
    date_creation TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE role (
    id_role BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_role VARCHAR(30) NOT NULL,
    libelle VARCHAR(100) NOT NULL
);

CREATE TABLE etudiant (
    id_etudiant BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule VARCHAR(50) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    date_naissance DATE,
    lieu_naissance VARCHAR(150),
    sexe VARCHAR(20),
    telephone VARCHAR(30),
    email VARCHAR(254)
);

CREATE TABLE dossier_etudiant (
    id_etudiant BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule VARCHAR(40) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    date_creation TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE demande_inscription_enseignant (
    id_demande BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    mot_de_passe_hash VARCHAR(255) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    date_demande TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE filiere (
    id_filiere BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    nom VARCHAR(150) NOT NULL,
    libelle VARCHAR(150),
    id_departement BIGINT,
    CONSTRAINT fk_filiere_departement
        FOREIGN KEY (id_departement) REFERENCES departement (id_departement)
);

CREATE TABLE niveau (
    id_niveau BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    libelle VARCHAR(100) NOT NULL,
    id_filiere BIGINT,
    CONSTRAINT uq_niveau_id_filiere UNIQUE (id_niveau, id_filiere),
    CONSTRAINT fk_niveau_filiere
        FOREIGN KEY (id_filiere) REFERENCES filiere (id_filiere)
);

CREATE TABLE semestre (
    id_semestre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    libelle VARCHAR(100) NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    id_annee BIGINT NOT NULL,
    CONSTRAINT uq_semestre_id_annee UNIQUE (id_semestre, id_annee),
    CONSTRAINT fk_semestre_annee
        FOREIGN KEY (id_annee) REFERENCES annee_academique (id_annee)
);

CREATE TABLE unite_enseignement (
    id_ue BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    libelle VARCHAR(150) NOT NULL,
    description TEXT,
    id_semestre BIGINT,
    CONSTRAINT fk_unite_enseignement_semestre
        FOREIGN KEY (id_semestre) REFERENCES semestre (id_semestre)
);

CREATE TABLE element_constitutif (
    id_ec BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    libelle VARCHAR(150) NOT NULL,
    description TEXT,
    coefficient NUMERIC NOT NULL,
    id_ue BIGINT,
    CONSTRAINT fk_element_constitutif_ue
        FOREIGN KEY (id_ue) REFERENCES unite_enseignement (id_ue)
);

CREATE TABLE groupe (
    id_groupe BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    libelle VARCHAR(120) NOT NULL,
    id_annee BIGINT NOT NULL,
    id_filiere BIGINT NOT NULL,
    id_niveau BIGINT NOT NULL,
    CONSTRAINT fk_groupe_annee
        FOREIGN KEY (id_annee) REFERENCES annee_academique (id_annee),
    CONSTRAINT fk_groupe_filiere
        FOREIGN KEY (id_filiere) REFERENCES filiere (id_filiere),
    CONSTRAINT fk_groupe_niveau
        FOREIGN KEY (id_niveau) REFERENCES niveau (id_niveau),
    CONSTRAINT fk_groupe_niveau_filiere
        FOREIGN KEY (id_niveau, id_filiere) REFERENCES niveau (id_niveau, id_filiere),
    CONSTRAINT uq_groupe_id_annee UNIQUE (id_groupe, id_annee)
);

CREATE TABLE enseignant (
    id_enseignant BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule VARCHAR(50) NOT NULL,
    specialite VARCHAR(150),
    id_utilisateur BIGINT NOT NULL,
    CONSTRAINT uq_enseignant_utilisateur UNIQUE (id_utilisateur),
    CONSTRAINT fk_enseignant_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE directeur_etudes (
    id_directeur_etudes BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur BIGINT NOT NULL,
    CONSTRAINT uq_directeur_etudes_utilisateur UNIQUE (id_utilisateur),
    CONSTRAINT fk_directeur_etudes_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE inscription (
    id_inscription BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_inscription DATE NOT NULL,
    statut VARCHAR(20) NOT NULL,
    id_annee BIGINT NOT NULL,
    id_etudiant BIGINT NOT NULL,
    id_groupe BIGINT NOT NULL,
    CONSTRAINT fk_inscription_annee
        FOREIGN KEY (id_annee) REFERENCES annee_academique (id_annee),
    CONSTRAINT fk_inscription_etudiant
        FOREIGN KEY (id_etudiant) REFERENCES etudiant (id_etudiant),
    CONSTRAINT fk_inscription_groupe
        FOREIGN KEY (id_groupe) REFERENCES groupe (id_groupe)
);

CREATE TABLE inscription_etudiant (
    id_inscription BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statut VARCHAR(20) NOT NULL,
    date_inscription DATE NOT NULL,
    id_annee BIGINT NOT NULL,
    id_etudiant BIGINT NOT NULL,
    id_groupe BIGINT NOT NULL,
    CONSTRAINT fk_inscription_etudiant_annee
        FOREIGN KEY (id_annee) REFERENCES annee_academique (id_annee),
    CONSTRAINT fk_inscription_etudiant_dossier
        FOREIGN KEY (id_etudiant) REFERENCES dossier_etudiant (id_etudiant),
    CONSTRAINT fk_inscription_etudiant_groupe
        FOREIGN KEY (id_groupe) REFERENCES groupe (id_groupe),
    CONSTRAINT fk_inscription_etudiant_groupe_annee
        FOREIGN KEY (id_groupe, id_annee) REFERENCES groupe (id_groupe, id_annee),
    CONSTRAINT uq_inscription_etudiant_groupe_annee
        UNIQUE (id_etudiant, id_groupe, id_annee)
);

CREATE TABLE enseignement (
    id_enseignement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volume_horaire_prevu NUMERIC,
    statut VARCHAR(20) NOT NULL,
    id_ec BIGINT NOT NULL,
    id_enseignant BIGINT NOT NULL,
    id_groupe BIGINT NOT NULL,
    id_semestre BIGINT NOT NULL,
    CONSTRAINT fk_enseignement_ec
        FOREIGN KEY (id_ec) REFERENCES element_constitutif (id_ec),
    CONSTRAINT fk_enseignement_enseignant
        FOREIGN KEY (id_enseignant) REFERENCES enseignant (id_enseignant),
    CONSTRAINT fk_enseignement_groupe
        FOREIGN KEY (id_groupe) REFERENCES groupe (id_groupe),
    CONSTRAINT fk_enseignement_semestre
        FOREIGN KEY (id_semestre) REFERENCES semestre (id_semestre)
);

CREATE TABLE affectation_enseignement (
    id_affectation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_affectation TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    id_annee BIGINT NOT NULL,
    id_ec BIGINT NOT NULL,
    id_groupe BIGINT NOT NULL,
    id_semestre BIGINT NOT NULL,
    id_utilisateur BIGINT NOT NULL,
    CONSTRAINT uq_affectation_scope UNIQUE (id_annee, id_ec, id_groupe),
    CONSTRAINT fk_affectation_annee
        FOREIGN KEY (id_annee) REFERENCES annee_academique (id_annee),
    CONSTRAINT fk_affectation_ec
        FOREIGN KEY (id_ec) REFERENCES element_constitutif (id_ec),
    CONSTRAINT fk_affectation_groupe
        FOREIGN KEY (id_groupe) REFERENCES groupe (id_groupe),
    CONSTRAINT fk_affectation_groupe_annee
        FOREIGN KEY (id_groupe, id_annee) REFERENCES groupe (id_groupe, id_annee),
    CONSTRAINT fk_affectation_semestre_annee
        FOREIGN KEY (id_semestre, id_annee) REFERENCES semestre (id_semestre, id_annee),
    CONSTRAINT fk_affectation_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE composition_ue (
    id_ue BIGINT NOT NULL,
    id_ec BIGINT NOT NULL,
    coefficient NUMERIC NOT NULL,
    ordre INTEGER,
    CONSTRAINT pk_composition_ue PRIMARY KEY (id_ue, id_ec),
    CONSTRAINT ck_composition_coefficient_positif CHECK (coefficient > 0),
    CONSTRAINT fk_composition_ue_unite
        FOREIGN KEY (id_ue) REFERENCES unite_enseignement (id_ue),
    CONSTRAINT fk_composition_ue_ec
        FOREIGN KEY (id_ec) REFERENCES element_constitutif (id_ec)
);

CREATE TABLE evaluation (
    id_evaluation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(200) NOT NULL,
    categorie VARCHAR(20) NOT NULL,
    date_evaluation DATE,
    bareme NUMERIC NOT NULL,
    statut_publication VARCHAR(20) NOT NULL,
    id_enseignement BIGINT NOT NULL,
    CONSTRAINT fk_evaluation_enseignement
        FOREIGN KEY (id_enseignement) REFERENCES enseignement (id_enseignement)
);

CREATE TABLE evaluation_cours (
    id_evaluation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(150) NOT NULL,
    date_evaluation DATE NOT NULL,
    coefficient NUMERIC NOT NULL,
    categorie VARCHAR(20) NOT NULL DEFAULT 'DEVOIR'
        CHECK (categorie IN ('INTERROGATION', 'DEVOIR', 'EXAMEN')),
    bareme NUMERIC NOT NULL DEFAULT 20 CHECK (bareme = 20),
    statut VARCHAR(20) NOT NULL,
    statut_publication VARCHAR(20) NOT NULL DEFAULT 'BROUILLON'
        CHECK (statut_publication IN ('BROUILLON', 'PUBLIEE')),
    id_affectation BIGINT NOT NULL,
    CONSTRAINT fk_evaluation_cours_affectation
        FOREIGN KEY (id_affectation) REFERENCES affectation_enseignement (id_affectation)
);

CREATE TABLE note (
    id_note BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valeur NUMERIC,
    statut_presence VARCHAR(30) NOT NULL,
    commentaire TEXT,
    date_saisie TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    date_modification TIMESTAMP WITHOUT TIME ZONE,
    id_evaluation BIGINT NOT NULL,
    id_inscription BIGINT NOT NULL,
    CONSTRAINT fk_note_evaluation
        FOREIGN KEY (id_evaluation) REFERENCES evaluation (id_evaluation),
    CONSTRAINT fk_note_inscription
        FOREIGN KEY (id_inscription) REFERENCES inscription (id_inscription)
);

CREATE TABLE note_evaluation (
    id_evaluation BIGINT NOT NULL,
    id_inscription BIGINT NOT NULL,
    valeur NUMERIC NOT NULL,
    date_saisie TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_note_evaluation_inscription PRIMARY KEY (id_evaluation, id_inscription),
    CONSTRAINT ck_note_evaluation_valeur CHECK (valeur >= 0 AND valeur <= 20),
    CONSTRAINT fk_note_evaluation_cours
        FOREIGN KEY (id_evaluation) REFERENCES evaluation_cours (id_evaluation),
    CONSTRAINT fk_note_evaluation_inscription
        FOREIGN KEY (id_inscription) REFERENCES inscription_etudiant (id_inscription)
);

CREATE TABLE historique_note (
    id_historique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ancienne_valeur NUMERIC,
    nouvelle_valeur NUMERIC,
    motif TEXT NOT NULL,
    date_modification TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    id_note BIGINT NOT NULL,
    id_utilisateur BIGINT NOT NULL,
    CONSTRAINT fk_historique_note_note
        FOREIGN KEY (id_note) REFERENCES note (id_note),
    CONSTRAINT fk_historique_note_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE seance_cours (
    id_seance BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_seance DATE NOT NULL,
    heure_debut TIME WITHOUT TIME ZONE NOT NULL,
    heure_fin TIME WITHOUT TIME ZONE NOT NULL,
    contenu_aborde TEXT,
    volume_horaire_realise NUMERIC,
    id_enseignement BIGINT NOT NULL,
    CONSTRAINT fk_seance_cours_enseignement
        FOREIGN KEY (id_enseignement) REFERENCES enseignement (id_enseignement)
);

CREATE TABLE chapitre (
    id_chapitre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(200) NOT NULL,
    description TEXT,
    ordre INTEGER,
    id_enseignement BIGINT NOT NULL,
    CONSTRAINT fk_chapitre_enseignement
        FOREIGN KEY (id_enseignement) REFERENCES enseignement (id_enseignement)
);

CREATE TABLE chapitre_cours (
    id_chapitre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(150) NOT NULL,
    ordre INTEGER NOT NULL,
    progression VARCHAR(20) NOT NULL,
    date_mise_a_jour TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    id_affectation BIGINT NOT NULL,
    CONSTRAINT fk_chapitre_cours_affectation
        FOREIGN KEY (id_affectation) REFERENCES affectation_enseignement (id_affectation)
);

CREATE TABLE suivi_pedagogique_seance (
    id_seance BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_seance TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    contenu VARCHAR(500) NOT NULL,
    date_creation TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    id_affectation BIGINT NOT NULL,
    CONSTRAINT fk_suivi_seance_affectation
        FOREIGN KEY (id_affectation) REFERENCES affectation_enseignement (id_affectation)
);

CREATE TABLE suivi_pedagogique_absence (
    id_absence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    justifiee BOOLEAN NOT NULL,
    motif VARCHAR(500),
    date_saisie TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    id_etudiant BIGINT NOT NULL,
    id_seance BIGINT NOT NULL,
    CONSTRAINT fk_suivi_absence_dossier
        FOREIGN KEY (id_etudiant) REFERENCES dossier_etudiant (id_etudiant),
    CONSTRAINT fk_suivi_absence_seance
        FOREIGN KEY (id_seance) REFERENCES suivi_pedagogique_seance (id_seance),
    CONSTRAINT uq_absence_student_session UNIQUE (id_etudiant, id_seance)
);

CREATE TABLE journal_audit (
    id_audit BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(100) NOT NULL,
    type_entite VARCHAR(100) NOT NULL,
    id_entite VARCHAR(100),
    date_action TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    details TEXT,
    id_utilisateur BIGINT,
    CONSTRAINT fk_journal_audit_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE rapport_genere (
    id_rapport BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_rapport VARCHAR(100) NOT NULL,
    date_generation TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    format VARCHAR(10) NOT NULL,
    id_utilisateur BIGINT NOT NULL,
    CONSTRAINT fk_rapport_genere_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);

CREATE TABLE utilisateur_role (
    id_utilisateur BIGINT NOT NULL,
    id_role BIGINT NOT NULL,
    date_attribution TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_utilisateur_role PRIMARY KEY (id_utilisateur, id_role),
    CONSTRAINT fk_utilisateur_role_utilisateur
        FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_utilisateur_role_role
        FOREIGN KEY (id_role) REFERENCES role (id_role)
);

CREATE UNIQUE INDEX uq_utilisateur_email_ci
    ON utilisateur (LOWER(email));

CREATE UNIQUE INDEX uq_role_code
    ON role (code_role);

CREATE UNIQUE INDEX uq_dossier_etudiant_matricule_ci
    ON dossier_etudiant (UPPER(matricule));
CREATE UNIQUE INDEX uq_departement_code_ci
    ON departement (UPPER(code));
CREATE UNIQUE INDEX uq_filiere_code_ci
    ON filiere (UPPER(code));
CREATE UNIQUE INDEX uq_unite_enseignement_code_ci
    ON unite_enseignement (UPPER(code));
CREATE UNIQUE INDEX uq_element_constitutif_code_ci
    ON element_constitutif (UPPER(code));
CREATE UNIQUE INDEX uq_niveau_filiere_code_ci
    ON niveau (id_filiere, UPPER(code));
CREATE UNIQUE INDEX uq_groupe_scope_code_ci
    ON groupe (id_annee, id_filiere, id_niveau, UPPER(code));
